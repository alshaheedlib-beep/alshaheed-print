export const dir = (lang) => (lang === 'ar' ? 'rtl' : 'ltr');

export function makeT(lang) {
  const i = lang === 'en' ? 1 : 0;
  return (key, vars) => {
    let s = D[key] ? D[key][i] : key;
    if (vars) for (const [k, v] of Object.entries(vars)) s = s.replaceAll(`{${k}}`, String(v));
    return s;
  };
}

